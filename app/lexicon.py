@dataclass(frozen=True)
class Rule:
    """규칙 하나. frozen=True : 만든 뒤에는 바꿀 수 없음(실수 방지)."""

    rid: str              # 규칙 이름 (로그·디버깅용)
    category: str         # config.CATEGORIES 중 하나
    weight: int           # 가중치. 높을수록 "특허 단서일 확률이 높다" 는 뜻
    pattern: re.Pattern   # 컴파일된 정규식
    hint: str             # 왜 특허 관점에서 의미가 있는지 (노트 주석에 그대로 들어감)
    # 실제 '공개' 에 해당하는가. 지식재산을 언급하기만 한 문장(예: "특허 출원 0건")은
    # 참고 정보일 뿐 신규성을 깨뜨리지 않으므로 자동 구제 대상에서 뺍니다.
    disclosure: bool = True


def _r(rid, category, weight, pattern, hint, flags=re.I, disclosure=True):
    """Rule 을 한 줄로 만들기 위한 짧은 도우미."""
    return Rule(rid, category, weight, re.compile(pattern, flags), hint, disclosure)


