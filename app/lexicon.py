# 기술적 실질을 담보하는 카테고리. 경영 단어가 있어도 이 신호가 같은 구간에 있으면
# 곧바로 걸러내지 않습니다.
TECHNICAL_CATEGORIES = {"구성·구조", "제어·알고리즘", "공정·방법"}


@dataclass
class Hit:
    """규칙 하나가 문단의 어느 구간에 걸렸는지."""

    rid: str
    category: str
    weight: int
    span: tuple[int, int]     # (시작, 끝) 글자 위치
    matched: str              # 실제로 걸린 글자
    hint: str
    disclosure: bool = False  # 진짜 '공개' 신호인가


def is_business_noise(text: str, hits: list[Hit],
                      span: tuple[int, int] | None = None) -> bool:
    """지목된 구간이 기술적 실질 없이 경영 지표만 담고 있는가.

    판단 범위는 문단 전체가 아니라 **인용된 구간(span)** 입니다.
    한 문단이 "매출 비중 34% → 51% 상승. 조립·물류 장비 중심 구조에서 …" 처럼
    경영 문장과 기술 문장을 함께 담는 일이 흔한데, 문단 전체를 보면
    뒤쪽의 '구조' 때문에 앞쪽 매출 수치까지 기술 후보로 통과해 버립니다.

    숫자가 있다는 이유만으로는 판단하지 않습니다. 매출·단가도 숫자를 달고 다니므로,
    구성·제어·공정 신호가 구간 안에 하나도 없을 때만 경영 정보로 봅니다.
    """
    lo, hi = span if span else (0, len(text))
    if not NOISE.search(text[lo:hi]):
        return False
    for h in hits:
        if h.category not in TECHNICAL_CATEGORIES:
            continue
        if not (h.span[1] <= lo or h.span[0] >= hi):   # 구간과 겹치는 기술 신호가 있으면
            return False
    return True


# ═════════════════════════════════════════════════════════════════
# 스캔과 점수
# ═════════════════════════════════════════════════════════════════
def scan(text: str) -> list[Hit]:
    """문단 하나에서 RULES 에 걸리는 모든 구간을 찾아 Hit 목록으로 돌려준다."""
    hits: list[Hit] = []
    for rule in RULES:
        for m in rule.pattern.finditer(text):
            if not m.group(0).strip():
                continue
            hits.append(
                Hit(rule.rid, rule.category, rule.weight, m.span(), m.group(0),
                    rule.hint, rule.disclosure and rule.category == "공개이력")
            )
    return hits


def score(text: str, hits: list[Hit]) -> int:
    """LLM 에 넘길 우선순위 점수. 최종 등급이 아니라 '얼마나 수상한가' 의 척도."""
    if not hits:
        return 0
    base = sum(h.weight for h in hits)
    # 서로 다른 카테고리가 겹칠수록 발명 소재일 확률이 올라갑니다
    base += 4 * (len({h.category for h in hits}) - 1)
    noise = len(NOISE.findall(text))
    if noise:
        base -= 6 * noise
    return max(base, 0)


def categories_of(hits: list[Hit]) -> list[str]:
    """Hit 목록에서 카테고리 이름만 중복 없이 뽑는다 (등장 순서 유지)."""
    seen: list[str] = []
    for h in hits:
        if h.category not in seen:
            seen.append(h.category)
    return seen


def has_disclosure_risk(hits: list[Hit]) -> bool:
    """실제로 신규성을 깨뜨릴 수 있는 공개 신호가 있는가."""
    return any(h.disclosure for h in hits)
