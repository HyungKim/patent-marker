@dataclass
class RunOptions:
    """분석을 한 번 실행할 때의 옵션 묶음.

    웹 화면의 체크박스 값이 main.py 에서 이 객체로 바뀌어
    analyze → merge → mark 단계로 전달됩니다.
    """

    model: str = MODEL
    think: bool = THINK

    # 판정 기준: "strict" 확실한 것만(기본) / "broad" 빠짐없이.  (웹 화면: '판정 기준', 명령행 --mode)
    mode: str = MODE

    # 규칙 사전에 걸리지 않은 문단도 모델에게 보낼지. None 이면 판정 기준의 기본값(SCAN_ALL_DEFAULT)을 따른다.
    # 끄면 빠르지만 사전에 없는 새로운 표현은 놓칩니다.       (웹 화면: '전체 문단 검사')
    scan_all_paragraphs: bool | None = None

    # 형광펜 구간 뒤에 【출원검토필요】 문구도 붙일지. 흑백 인쇄용 선택 사항 — 기본은 끔.
    # (색상 안내는 첫 슬라이드의 범례 상자가 맡습니다)        (웹 화면: '문구도 표시')
    tag_marks: bool = False

    # 검토 학습 적용 여부 (문단 기억·제외 사전/자동 규칙·유사 사례 검색) 와 뜻 기준 검색(bge-m3) 사용 여부.
    # 화면의 체크박스 / 명령행 --no-learn, --no-embed 와 연결. (웹 화면: '검토 학습 적용', '뜻 기준 검색')
    learn: bool = LEARN
    learn_embed: bool = LEARN_EMBED

    # 분석 전에 원본에 있던 형광펜을 걷어낼지 (app/prehl.py). 원본 파일은 바뀌지 않습니다.
    # (웹 화면: '원본 형광펜 지우고 시작', 명령행 --keep-highlights 로 끔)
    strip_highlights: bool = STRIP_HIGHLIGHTS

    # 공개 관련 표시 (전시·논문·출시 신호 → C 공개 관련정보). 끄면 공개 규칙·공개 후보를 쓰지 않아 조금 빠르다.
    # (웹 화면: '공개 관련 표시', 명령행 --no-disclosure 로 끔)
    disclosure: bool = DISCLOSURE

    # 이 글자 수보다 짧은 문단은 분석하지 않습니다. (예: "01", "→" 같은 장식 글자)
    min_chars: int = 6

    # 이 문구와 정확히 같은 문단은 건너뜁니다.
    skip_labels: tuple[str, ...] = field(
        default_factory=lambda: ("대외비", "CONFIDENTIAL", "목차", "감사합니다", "Thank you")
    )

    def __post_init__(self) -> None:
        if self.mode not in ("strict", "broad"):
            self.mode = "strict"
        if self.scan_all_paragraphs is None:
            self.scan_all_paragraphs = SCAN_ALL_DEFAULT[self.mode]
