"""
config.py ─ 프로그램 전체에서 공통으로 쓰는 "설정값" 모음
=====================================================================

[이 파일이 하는 일]
  동작 로직은 거의 없고, 다른 파일들이 참고하는 숫자·문자열·색상 같은 '상수'만
  모아 두었습니다. 무언가를 바꾸고 싶을 때 가장 먼저 열어 볼 파일입니다.

      모델을 바꾸고 싶다 ................ MODEL
      형광펜 색을 바꾸고 싶다 ........... GRADE_COLOR
      '출원검토필요' 표현을 바꾸고 싶다 .. LEGEND_TITLE · TAG_TEXT
      웹 화면 주소(포트)를 바꾸고 싶다 ... PORT

[환경 변수란?]
  os.environ.get("PM_MODEL", "qwen3:8b") 는
  "PM_MODEL 이라는 환경 변수가 있으면 그 값을, 없으면 'qwen3:8b' 를 쓴다" 는 뜻입니다.
  코드를 고치지 않고 실행 시점에 값을 바꾸는 용도입니다. (보통은 건드릴 일이 없습니다.)

      macOS / Linux :  PM_MODEL=모델명 bash run.sh
      Windows       :  set PM_MODEL=모델명   (엔터 후)   run.bat
"""
from __future__ import annotations

import os
from dataclasses import dataclass, field

# ─────────────────────────────────────────────────────────────────
# 1. 온디바이스 LLM (Ollama) 관련
# ─────────────────────────────────────────────────────────────────
# Ollama 는 "LLM 을 내 컴퓨터 안에서 실행해 주는 프로그램" 입니다.
# 우리 프로그램은 Ollama 에게 HTTP 로 질문을 보내고 답을 받습니다.
# 127.0.0.1 은 "내 컴퓨터 자신" 을 뜻하는 주소라서, 외부로 나가는 통신이 아닙니다.
OLLAMA_HOST = os.environ.get("PM_OLLAMA_HOST", "http://127.0.0.1:11434")

# 사용할 모델 이름. 터미널에서 `ollama list` 를 치면 내려받은 모델 목록이 보입니다.
#   qwen3:8b → 기본. 가볍고 빠름(약 5GB). GPU 없는 PC·메모리 16GB 에서도 실용적
#   나중에 PC 사양이 좋아져 더 큰 모델로 바꿀 때: ollama pull 모델명 후 아래 값을 바꾸면 끝
MODEL = os.environ.get("PM_MODEL", "qwen3:8b")

# Qwen3 의 '생각하기(thinking)' 모드. 켜면 정확도가 조금 오르지만 3~5배 느려집니다.
# 기본은 끔. 웹 화면의 '추론 모드' 체크박스와 연결되어 있습니다.
THINK = os.environ.get("PM_THINK", "0") == "1"

# 모델이 한 번에 읽을 수 있는 분량(토큰 수). 크게 잡을수록 메모리를 더 씁니다.
NUM_CTX = int(os.environ.get("PM_NUM_CTX", "8192"))

# 답변의 무작위성. 0 에 가까울수록 매번 같은 답을 냅니다. 분석 용도라 낮게 둡니다.
TEMPERATURE = float(os.environ.get("PM_TEMPERATURE", "0.1"))

# 슬라이드 한 장 분석에 허용하는 최대 대기 시간(초). 느린 PC 라면 늘리세요.
REQUEST_TIMEOUT = int(os.environ.get("PM_TIMEOUT", "600"))

# ─────────────────────────────────────────────────────────────────
# 2. 웹 서버 (브라우저 화면) 관련
# ─────────────────────────────────────────────────────────────────
# HOST 를 127.0.0.1 로 고정했기 때문에 "같은 컴퓨터의 브라우저" 에서만 접속됩니다.
# 다른 PC 에서 접속되게 하려면 0.0.0.0 으로 바꿔야 하지만, 보안상 권장하지 않습니다.
HOST = "127.0.0.1"
PORT = int(os.environ.get("PM_PORT", "8765"))   # 접속 주소: http://127.0.0.1:8765

# ─────────────────────────────────────────────────────────────────
# 3. 등급과 색상
# ─────────────────────────────────────────────────────────────────
# 결과에 표시되는 등급은 A · B · C 세 가지이고, 형광펜 색이 곧 등급입니다.
#   A : 구체적 기술 수단 + 효과가 함께 드러남     → 즉시 출원 검토
#   B : 수단은 안 적혀 있지만 존재가 강하게 시사됨 → 발명 발굴 필요
#   C : 공개 관련정보 — 전시·논문 등으로 이미 밖에 나간 내용 → 공개전 출원완료 필요
#
# C 는 모델이 직접 고르는 등급이 아니라, '공개 신호'(disclosure_risk)가 붙은 구간에
# 자동으로 매겨집니다. 모델이 스스로 매기는 C(배경·참고 수준)는 후보가 아니므로
# merge.py 가 결과에서 걸러 냅니다.
#
# 색상은 6자리 16진수 RGB 입니다 (예: FFD54F = 노랑). '#' 은 붙이지 않습니다.
GRADE_COLOR = {
    "A": "FFD54F",   # 앰버(노랑)
    "B": "9FD8F5",   # 하늘색
    "C": "FF9E80",   # 살구색 (공개 관련정보)
}
GRADE_LABEL = {
    "A": "즉시 출원 검토",
    "B": "발명 발굴 필요",
    "C": "공개 관련정보",
}

# 형광펜은 전부 밝은 색이라, 원래 글자가 흰색(어두운 배경 슬라이드)이면 읽히지 않습니다.
# 그런 경우 글자색을 이 색으로 바꿔 줍니다.
MARKED_TEXT_COLOR = "141A22"

# ─────────────────────────────────────────────────────────────────
# 4. '출원검토필요' 표시
# ─────────────────────────────────────────────────────────────────
# 형광펜 구간이 곧 "출원 검토가 필요한 곳" 입니다. 원본을 건드리는 것은 형광펜과
# 첫 슬라이드의 색상 범례 상자 하나뿐이고, 그 밖에는 아무것도 덧붙이지 않습니다.
SLIDE_LEGEND = True
LEGEND_TITLE = "출원검토필요 표시 안내"
LEGEND_NAME = "출원검토필요 범례"       # 도형 이름 (검토 반영 때 도구가 넣은 것임을 알아보는 표식)
TAG_COLOR = "C62828"        # 진한 빨강 (범례 테두리·문구 색)

# [선택] 형광펜 구간 바로 뒤에 붙이는 문구. 흑백 인쇄물처럼 색을 볼 수 없을 때를 위한
# 옵션이며 기본은 끔 (웹 화면 '문구도 표시' 체크박스 / RunOptions.tag_marks).
TAG_TEXT = "【출원검토필요】"

# 아래는 **예전 버전이 만든 마킹본을 [검토 반영] 에 올렸을 때 알아보기 위한** 표식입니다.
# 지금은 배지를 붙이지 않지만, 예전에 만든 파일에는 배지가 들어 있을 수 있습니다.
LEGACY_TAG_TEXTS = ("【특허검토필요】",)
LEGACY_BADGE_TEXTS = ("출원검토필요", "특허검토필요")
LEGACY_BADGE_NAMES = ("출원검토필요 배지", "특허검토필요 배지")

# ─────────────────────────────────────────────────────────────────
# 5. 분류(카테고리)
# ─────────────────────────────────────────────────────────────────
# "이 구간은 어떤 종류의 특허 단서인가" 를 표시하는 이름표입니다.
# analyze.py 의 JSON 스키마가 이 목록을 그대로 참조하므로, 이름을 바꾸면
# lexicon.py 의 규칙 카테고리도 같이 바꿔야 합니다.
CATEGORIES = [
    "구성·구조",
    "수치·범위한정",
    "제어·알고리즘",
    "공정·방법",
    "효과만기재",
    "독자성주장",
    "최적화·조건확립",
    "문제해결",
    "비교우위",
    "블랙박스용어",
    "공개이력",
]


# ─────────────────────────────────────────────────────────────────
# 6. 검토 반영 (사전·예시 보강) 데이터
# ─────────────────────────────────────────────────────────────────
# 사람이 형광펜을 교정한 '검토완료본' 을 웹 화면의 [검토 반영] 탭에 올리면,
# 교정 내역이 아래 폴더에 쌓입니다. 이 데이터는 PC 밖으로 나가지 않습니다.
#   analyses/         분석할 때마다 자동 저장되는 판정 기록 (검토본과 비교용)
#   dataset.jsonl     확정된 교정 내역 (한 줄 = 한 건)
#   examples.json     판정 프롬프트에 자동 주입되는 모범답안·반례 모음
#   extra_rules.json  [사전에 추가] 버튼으로 등록한 표현 (다음 분석부터 반드시 잡음)
from pathlib import Path as _Path

_ROOT = _Path(__file__).resolve().parents[1]        # patent_marker 폴더

REVIEW_DIR = _Path(os.environ.get("PM_REVIEW_DIR", str(_ROOT / "review_data")))

# ─────────────────────────────────────────────────────────────────
# 7. 브라우저 업로드 없이 파일을 주고받는 폴더
# ─────────────────────────────────────────────────────────────────
# 회사 PC 처럼 브라우저의 파일 올리기가 막힌 곳에서는 여기에 PPTX 를 복사해 두면
# 웹 화면의 목록에 나타나고, 결과는 output 폴더에 바로 저장됩니다. (app/local.py)
#   input\    분석할 PPTX 를 넣는 곳 (검토완료본도 여기)
#   output\   마킹된 결과가 저장되는 곳  →  이름_특허마킹.pptx
INPUT_DIR = _Path(os.environ.get("PM_INPUT_DIR", str(_ROOT / "input")))
OUTPUT_DIR = _Path(os.environ.get("PM_OUTPUT_DIR", str(_ROOT / "output")))


@dataclass
class RunOptions:
    """분석을 한 번 실행할 때의 옵션 묶음.

    웹 화면의 체크박스 값이 main.py 에서 이 객체로 바뀌어
    analyze → merge → mark 단계로 전달됩니다.
    """

    model: str = MODEL
    think: bool = THINK

    # 규칙 사전에 걸리지 않은 문단도 모델에게 보낼지.
    # 끄면 빠르지만 사전에 없는 새로운 표현은 놓칩니다.       (웹 화면: '전체 문단 검사')
    scan_all_paragraphs: bool = True

    # 형광펜 구간 뒤에 【출원검토필요】 문구도 붙일지. 흑백 인쇄용 선택 사항 — 기본은 끔.
    # (색상 안내는 첫 슬라이드의 범례 상자가 맡습니다)        (웹 화면: '문구도 표시')
    tag_marks: bool = False

    # 이 글자 수보다 짧은 문단은 분석하지 않습니다. (예: "01", "→" 같은 장식 글자)
    min_chars: int = 6

    # 이 문구와 정확히 같은 문단은 건너뜁니다.
    skip_labels: tuple[str, ...] = field(
        default_factory=lambda: ("대외비", "CONFIDENTIAL", "목차", "감사합니다", "Thank you")
    )
